-- Personal document roots belong to one account on this computer. Project roots also belong to its one Runtime.
CREATE TABLE node_content.document_roots (
  organization_id uuid NOT NULL, node_id uuid NOT NULL, scope_kind text NOT NULL CHECK(scope_kind IN ('personal','project')),
  scope_id uuid NOT NULL, root_id uuid PRIMARY KEY, volume_id uuid NOT NULL REFERENCES node_content.volume(volume_id),
  runtime_id uuid, writer_epoch bigint NOT NULL CHECK(writer_epoch>0), sequence bigint NOT NULL DEFAULT 0 CHECK(sequence>=0),
  ordinal integer NOT NULL DEFAULT 0 CHECK(ordinal>=0), revision bigint NOT NULL DEFAULT 0 CHECK(revision>=0),
  UNIQUE(organization_id,node_id,scope_kind,scope_id), UNIQUE(organization_id,root_id), CHECK ((sequence=0)=(ordinal=0)),
  CHECK((scope_kind='project')=(runtime_id IS NOT NULL)),
  FOREIGN KEY(organization_id,runtime_id) REFERENCES node_content.spaces(organization_id,runtime_id)
);
CREATE TABLE node_content.document_entries (
  catalog_id uuid PRIMARY KEY DEFAULT gen_random_uuid(), organization_id uuid NOT NULL, root_id uuid NOT NULL,
  runtime_id uuid, incarnation_id uuid NOT NULL, revision bigint NOT NULL CHECK(revision>0), doc_id text NOT NULL,
  directory_id text NOT NULL, name text NOT NULL, bytes bigint NOT NULL CHECK(bytes>=0), media_type text NOT NULL,
  modified_at_ms bigint NOT NULL CHECK(modified_at_ms>=0), owner_public_id bigint CHECK(owner_public_id>0),
  origin text NOT NULL CHECK(origin IN ('upload','transfer','legacy','admin')),
  state text NOT NULL CHECK(state IN ('active','trash','purged','missing','deleted')), trash_id text,
  trashed_at_ms bigint, purge_after_ms bigint, restored_at_ms bigint, purged_at_ms bigint,
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),lineage_root_id uuid,source_catalog_id uuid, UNIQUE(root_id,incarnation_id), UNIQUE(root_id,catalog_id),
  FOREIGN KEY(organization_id,root_id) REFERENCES node_content.document_roots(organization_id,root_id)
);
CREATE UNIQUE INDEX node_document_live_path ON node_content.document_entries(root_id,doc_id) WHERE state='active';
CREATE INDEX node_document_scope_page ON node_content.document_entries(root_id,modified_at_ms DESC,catalog_id);
CREATE TABLE node_content.document_events (
  organization_id uuid NOT NULL, root_id uuid NOT NULL, runtime_id uuid, id bigint GENERATED BY DEFAULT AS IDENTITY,
  catalog_id uuid, operation_id uuid, actor_public_id bigint, event_kind text NOT NULL, occurred_at timestamptz NOT NULL,
  detail jsonb NOT NULL, PRIMARY KEY(root_id,id),
  FOREIGN KEY(organization_id,root_id) REFERENCES node_content.document_roots(organization_id,root_id),
  FOREIGN KEY(root_id,catalog_id) REFERENCES node_content.document_entries(root_id,catalog_id)
);
CREATE INDEX node_document_events_page ON node_content.document_events(root_id,occurred_at DESC,id DESC);
CREATE TABLE node_content.document_receipts (
  organization_id uuid NOT NULL, root_id uuid NOT NULL, runtime_id uuid, operation_id uuid NOT NULL,
  direction text NOT NULL CHECK(direction IN ('source','target')), item_id text NOT NULL, counterpart_node_id uuid NOT NULL,
  catalog_id uuid, state text NOT NULL CHECK(state IN ('copied','failed')), occurred_at timestamptz NOT NULL,
  PRIMARY KEY(root_id,operation_id,direction,item_id),
  FOREIGN KEY(organization_id,root_id) REFERENCES node_content.document_roots(organization_id,root_id),
  FOREIGN KEY(root_id,catalog_id) REFERENCES node_content.document_entries(root_id,catalog_id)
);
CREATE FUNCTION node_content.enforce_document_root() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
  IF NOT EXISTS(SELECT FROM node_content.document_roots r WHERE r.root_id=NEW.root_id AND r.organization_id=NEW.organization_id
      AND r.runtime_id IS NOT DISTINCT FROM NEW.runtime_id) THEN RAISE EXCEPTION 'Document item is outside its scope'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER document_entry_owner BEFORE INSERT OR UPDATE ON node_content.document_entries FOR EACH ROW EXECUTE FUNCTION node_content.enforce_document_root();
CREATE TRIGGER document_event_owner BEFORE INSERT OR UPDATE ON node_content.document_events FOR EACH ROW EXECUTE FUNCTION node_content.enforce_document_root();
CREATE TRIGGER document_receipt_owner BEFORE INSERT OR UPDATE ON node_content.document_receipts FOR EACH ROW EXECUTE FUNCTION node_content.enforce_document_root();
