/** Generate browser-only file associations and SVG data from the pinned Material Icon Theme. */
import { createRequire } from 'node:module'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { generateManifest } from 'material-icon-theme'

const require = createRequire(import.meta.url)
const packageRoot = dirname(require.resolve('material-icon-theme/package.json'))
const target = fileURLToPath(new URL('../src/client/file-icons.data.ts', import.meta.url))
const manifest = generateManifest()
const sorted = object => Object.fromEntries(Object.entries(object).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0))
const aliases = object => Object.fromEntries(Object.entries(object).map(([key, value]) => [key.toLowerCase(), value]))
const names = sorted({ ...aliases(manifest.fileNames), ...manifest.fileNames })
const extensions = sorted({ ...aliases(manifest.fileExtensions), ...manifest.fileExtensions })
const ids = [...new Set([manifest.file, ...Object.values(names), ...Object.values(extensions)])].sort()
const images = {}
for (const id of ids) {
  const path = manifest.iconDefinitions[id].iconPath
  const svg = await readFile(join(packageRoot, 'dist', path))
  images[id] = 'data:image/svg+xml;base64,'+svg.toString('base64')
}
const packageManifest = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8'))
const license = await readFile(join(packageRoot, 'LICENSE'), 'utf8')
const quote = value => "'" + value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('\n', '\\n').replaceAll('\r', '\\r') + "'"
const objectSource = object => '{\n' + Object.entries(object).map(([key, value]) => '  '+quote(key)+': '+quote(value)+',').join('\n') + '\n}'
const commentLicense = license.trim().split('\n').map(line => line.replace(/(.{1,115})(?:\s+|$)/g, '$1\n').trimEnd()).join('\n')
const source = `/*! Material Icon Theme ${packageManifest.version}\n${commentLicense}\n*/\n/** Generated by scripts/generate-file-icons.mjs; do not edit associations or SVG data here. */\n\n/** Complete upstream filename associations. */\nexport const fileIconNames: Readonly<Record<string, string>> = ${objectSource(names)}\n\n/** Complete upstream compound-extension associations. */\nexport const fileIconExtensions: Readonly<Record<string, string>> = ${objectSource(extensions)}\n\n/** Locally packaged SVG images for every reachable file association. */\nexport const fileIconImages: Readonly<Record<string, string>> = ${objectSource(images)}\n\n/** Upstream fallback for an unrecognized filename and MIME type. */\nexport const defaultFileIcon = ${quote(manifest.file)}\n`
await writeFile(target, source)
await writeFile(fileURLToPath(new URL('../LICENSE.material-icon-theme', import.meta.url)), license)
console.log(JSON.stringify({version:packageManifest.version,filenames:Object.keys(names).length,extensions:Object.keys(extensions).length,icons:ids.length,sourceBytes:Buffer.byteLength(source)}))
